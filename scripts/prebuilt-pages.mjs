// CLEAR row 43: copy every prebuilt page (HTML, RSC payload, segment prefetch files) that `next build`
// wrote into .next/server/app to .open-next/assets/cdn-cgi/_prebuilt/, and write the page list to
// .open-next/prebuilt-pages.mjs for worker.ts. The worker then streams these files instead of letting
// OpenNext parse its ~640 KB cache entry per request (lib/edge.ts prebuiltAsset).
// Runs after `opennextjs-cloudflare build` (npm run cf:build / preview / deploy).
// Files end in .bin so Workers static assets never rewrites .html paths; /cdn-cgi/ is not served publicly.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const APP = ".next/server/app";
const OUT = ".open-next/assets/cdn-cgi/_prebuilt";
const manifest = JSON.parse(readFileSync(".next/prerender-manifest.json", "utf8"));

rmSync(OUT, { recursive: true, force: true });
const pages = {};
const skipped = [];
for (const [route, info] of Object.entries(manifest.routes)) {
  const file = route === "/" ? "index" : route.slice(1);
  const meta = existsSync(join(APP, `${file}.meta`)) ? JSON.parse(readFileSync(join(APP, `${file}.meta`), "utf8")) : null;
  // Only plain 200 app pages that never revalidate. Redirects (/garage), error pages and route handlers
  // (robots.txt, sitemap.xml) stay with OpenNext.
  const ok =
    !route.startsWith("/_") &&
    info.initialRevalidateSeconds === false &&
    typeof info.dataRoute === "string" &&
    meta &&
    (meta.status ?? 200) === 200 &&
    existsSync(join(APP, `${file}.html`)) &&
    existsSync(join(APP, `${file}.rsc`));
  if (!ok) {
    skipped.push(route);
    continue;
  }
  const copy = (from, to) => {
    mkdirSync(dirname(join(OUT, to)), { recursive: true });
    cpSync(join(APP, from), join(OUT, to));
  };
  copy(`${file}.html`, `${file}.html.bin`);
  copy(`${file}.rsc`, `${file}.rsc.bin`);
  const segments = [];
  for (const seg of meta.segmentPaths ?? []) {
    const src = `${file}.segments${seg}.segment.rsc`;
    if (!existsSync(join(APP, src))) continue;
    copy(src, `${file}.segments/${seg.replace(/^\//, "")}.segment.rsc.bin`);
    segments.push(seg);
  }
  const headers = {};
  for (const [k, v] of Object.entries(meta.headers ?? {})) {
    // Internal headers OpenNext does not send either.
    if (k === "x-next-cache-tags" || k === "x-middleware-set-cookie" || v === undefined) continue;
    headers[k] = String(v);
  }
  pages[route] = { file, headers, segments };
}

writeFileSync(
  ".open-next/prebuilt-pages.mjs",
  `// Generated by scripts/prebuilt-pages.mjs (CLEAR row 43). Do not edit.\nexport default ${JSON.stringify(pages, null, 1)};\n`,
);
console.log(`prebuilt-pages: ${Object.keys(pages).length} pages to ${OUT}; left to OpenNext: ${skipped.join(", ")}`);
